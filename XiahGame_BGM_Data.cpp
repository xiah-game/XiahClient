{
	int map_x = pos.x / 256;
	int map_y = -pos.z / 256;

	index %= 3;
	map_x %= 8;
	map_y %= 8;

	int i = g_MapBGMInfo_BGM[ (map_id - 1) * 8 * 8 * 3 + map_x + map_y * 8 * 3 + index * 8];
/*
	if( i == 0)
		return NULL;
*/
	i %= BGM_FILE_COUNT;

	return g_strBGMFile[i];
}

